/* ─── 内部: I2C 写命令/数据 ───
 * SSD1306 协议: 第一字节控制字节 (0x00=命令, 0x40=数据)
 *              第二字节才是实际数据
 * IOI2C 的 i2cWrite(addr, reg, len, data): reg 会先发, 然后发 data
 * 所以 reg=control, data[0]=实际字节
 */
static void oled_write(uint8_t control, uint8_t data)
{
    if (!g_oled_present) return;          /* OLED 未接, 跳过避免I2C超时 */
    i2cWrite(OLED_I2C_ADDR, control, 1, &data);
}

static void oled_cmd(uint8_t c)  { oled_write(0x00, c); }
static void oled_data(uint8_t d) { oled_write(0x40, d); }

